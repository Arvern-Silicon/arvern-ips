#!/usr/bin/env python3
"""Find uncovered toggle bits that are CONSTANT BY CONSTRUCTION and emit waivers.

A bit is constant by construction when the signal's only driver is a continuous
assignment (`assign x = ...;` or `wire [..] x = ...;`) and that bit position is a
sized literal, a replicated literal or a parameter in it -- e.g. the zero bits of a
compressed-immediate concatenation, or a reserved CSR field. Such a bit cannot
toggle in any test, so it is unreachable under THE RULE of waivers_cov.md, and the
generated reason names the driver line so the argument can be re-checked.

Anything the parser is not sure of is left alone (and counted): several drivers
(generate branches), a driver in an always block, an expression that is not a plain
concatenation, or widths that do not add up. A missed constant only leaves a point
in the hole list; a wrong one would hide a real hole, so the parser errs that way.

With Yosys on PATH the decision is made by elaboration instead of by text: each
coverage configuration (cov_const_cfg.coverage_configs(), the repository-specific
part next to this script) is elaborated with every
wire kept (`setattr -set keep`), flattened so constants also cross instance ports, and
optimised. A bit counts as constant only if Yosys ties it to 0/1 in EVERY instance of
its module in EVERY configuration (coverage is per source location, so a bit constant
in one instance but live in another is never waived). Keeping every wire is what
separates a constant bit from an alias of a live signal, which an elaborated netlist
otherwise merges into one net. --no-flatten optimises each module on its own;
--no-yosys forces the text parser.

Entries are generated through cov_waive.suggest_entries(), the same folding the
--suggest CLI uses, so each glob selects exactly the constant uncovered bits.

    cov_const.py <dats_dir>             summary of what would be waived
    cov_const.py <dats_dir> --write     (re)write the generated section of
                                        run/waivers_cov.md, between its markers
    cov_const.py <dats_dir> --no-flatten  per-module Yosys optimisation (no cross-hierarchy)
    cov_const.py <dats_dir> --no-yosys  use the text parser even if Yosys is installed
"""
import os
import re
import sys
import json
import shutil
import tempfile
import subprocess
import collections

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cov_report   # noqa: E402
import cov_waive    # noqa: E402
import cov_const_cfg as cfg   # noqa: E402  per repository: TOP, rtl_files(), coverage_configs()

BEGIN = '<!-- BEGIN generated by cov_const.py: do not edit by hand -->'
END = '<!-- END generated by cov_const.py -->'

LIT = re.compile(r"^(\d+)\s*'\s*[sS]?[bBoOdDhH]\s*[0-9a-fA-F_xXzZ?]+$")


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', lambda m: re.sub(r'[^\n]', ' ', m.group(0)), text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


class Source(object):
    """Drivers, declared widths and parameter names of one RTL file."""

    def __init__(self, path):
        with open(path, encoding='utf-8', errors='replace') as fh:
            raw = fh.read()
        self.text = strip_comments(raw)
        self.lines = raw.split('\n')
        self.params = set(re.findall(r'\b(?:parameter|localparam)\b[^;=]*?\b(\w+)\s*=', self.text))
        self.widths = {}
        decl = re.compile(r'\b(?:wire|reg|input|output|inout)\b(?:\s+(?:wire|reg|signed))*\s*'
                          r'(?:\[\s*(\d+)\s*:\s*(\d+)\s*\])?\s*(\w+)')
        for m in decl.finditer(self.text):
            hi, lo, name = m.group(1), m.group(2), m.group(3)
            if hi is not None:
                self.widths.setdefault(name, (int(hi), int(lo)))
            else:
                self.widths.setdefault(name, (0, 0))
        # Line ranges of generate regions: a constant driver there is only one of
        # several elaborations, so it is never trusted on its own.
        self.gen = [(self._line(m.start()), self._line(m.end()))
                    for m in re.finditer(r'\bgenerate\b.*?\bendgenerate\b', self.text, re.S)]
        self.drivers = collections.defaultdict(list)
        for m in re.finditer(r'\bassign\s+(\w+)\s*=\s*([^;]*);', self.text):
            self.drivers[m.group(1)].append((self._line(m.start()), m.group(2)))
        for m in re.finditer(r'\bwire\b(?:\s+signed)?\s*(?:\[[^\]]*\])?\s*(\w+)\s*=\s*([^;]*);', self.text):
            self.drivers[m.group(1)].append((self._line(m.start()), m.group(2)))

    def _line(self, pos):
        return self.text.count('\n', 0, pos) + 1

    def in_generate(self, line):
        return any(lo <= line <= hi for lo, hi in self.gen)

    def procedurally_assigned(self, name):
        return re.search(r'\b%s\b(?:\s*\[[^\]]*\])?\s*<?=(?!=)' % re.escape(name),
                         re.sub(r'\b(?:assign|wire)\b[^;]*;', '', self.text)) is not None


def split_top(s, sep=','):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '{([':
            depth += 1
        elif ch in '})]':
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    out.append(cur)
    return [x.strip() for x in out]


def elem(src, e):
    """(width, is_constant) of one concatenation element, or None if unsure."""
    e = e.strip()
    lit = LIT.match(e)
    if lit:
        return int(lit.group(1)), True
    m = re.match(r'^\{\s*(\d+)\s*\{(.*)\}\s*\}$', e, re.S)
    if m:                                               # replication {N{...}}
        inner = concat(src, '{' + m.group(2) + '}')
        if inner is None:
            return None
        return int(m.group(1)) * len(inner), all(inner)
    if e.startswith('{') and e.endswith('}'):
        inner = concat(src, e)
        return (len(inner), None) if inner is not None else None
    m = re.match(r'^(\w+)\s*\[\s*(\d+)\s*:\s*(\d+)\s*\]$', e)
    if m:
        return abs(int(m.group(2)) - int(m.group(3))) + 1, m.group(1) in src.params
    m = re.match(r'^(\w+)\s*\[\s*(\d+)\s*\]$', e)
    if m:
        return 1, m.group(1) in src.params
    m = re.match(r'^(\w+)$', e)
    if m and m.group(1) in src.widths and m.group(1) not in src.params:
        hi, lo = src.widths[m.group(1)]
        return hi - lo + 1, False
    return None


def concat(src, expr):
    """Per-bit constant flags, MSB first, of a sized expression, or None."""
    expr = expr.strip()
    lit = LIT.match(expr)
    if lit:
        return [True] * int(lit.group(1))
    if not (expr.startswith('{') and expr.endswith('}')):
        return None
    body = expr[1:-1]
    rep = re.match(r'^\{\s*(\d+)\s*\{(.*)\}\s*\}$', expr, re.S)
    if rep:                                             # the whole thing is a replication
        inner = concat(src, '{' + rep.group(2) + '}')
        return inner * int(rep.group(1)) if inner is not None else None
    if re.match(r'^\s*\d+\s*\{', body):
        return None
    flags = []
    for part in split_top(body):
        if part.startswith('{') and part.endswith('}') and not re.match(r'^\{\s*\d+\s*\{', part):
            sub = concat(src, part)
            if sub is None:
                return None
            flags += sub
            continue
        r = elem(src, part)
        if r is None or r[1] is None:
            return None
        flags += [r[1]] * r[0]
    return flags




def _ysig_bits(spec, widths):
    """RTLIL sigspec -> bits MSB first: ('w', wire, idx) or ('c', '0'|'1'|'x')."""
    spec = spec.strip()
    if spec.startswith('{'):
        bits = []
        for t in re.findall(r"\\\S+\s+\[\d+(?::\d+)?\]|\\\S+|\d+'[01xzm-]+|-?\d+",
                            spec[1:spec.rindex('}')]):
            sub = _ysig_bits(t, widths)
            if sub is None:
                return None
            bits += sub
        return bits
    m = re.match(r"^(\d+)'([01xzm-]+)$", spec)
    if m:
        return [('c', ch) for ch in m.group(2)]
    m = re.match(r'^(-?\d+)$', spec)                   # RTLIL integer constant: 32 bits
    if m:
        return [('c', ch) for ch in format(int(m.group(1)) & 0xFFFFFFFF, '032b')]
    # A bit/part select is written with a space before the bracket (\\w [3]); an array
    # element's own name has none (\\cfg[0]) and is a whole wire.
    m = re.match(r'^(\\\S+)\s+\[(\d+):(\d+)\]$', spec)
    if m:
        return [('w', m.group(1), i) for i in range(int(m.group(2)), int(m.group(3)) - 1, -1)]
    m = re.match(r'^(\\\S+)\s+\[(\d+)\]$', spec)
    if m:
        return [('w', m.group(1), int(m.group(2)))]
    m = re.match(r'^(\\\S+)$', spec)
    if m:
        w, off = widths.get(m.group(1), (1, 0))
        return [('w', m.group(1), i) for i in range(off + w - 1, off - 1, -1)]
    return None


def _rtlil_consts(body):
    """(widths, {wire: constant bit set}) of one RTLIL module body."""
    widths, const, alias = {}, collections.defaultdict(set), []
    for w in re.finditer(r'^\s*wire (?:width (\d+) )?(?:offset (\d+) )?(?:(?:input|output|inout) \d+ )?'
                         r'(?:signed )?(\\\S+)', body, re.M):
        widths[w.group(3)] = (int(w.group(1) or 1), int(w.group(2) or 0))
    for c in re.finditer(r'^\s*connect (.+)$', body, re.M):
        parts, depth, cut = c.group(1), 0, None
        for i, ch in enumerate(parts):
            if ch == '{':
                depth += 1
            elif ch == '}':
                depth -= 1
            elif ch == ' ' and depth == 0 and i > 0 and not re.match(r'\s*\[', parts[i:]):
                cut = i
                break
        if cut is None:
            continue
        lhs, rhs = _ysig_bits(parts[:cut], widths), _ysig_bits(parts[cut:], widths)
        if not lhs or not rhs or len(lhs) != len(rhs):
            continue
        for lb, rb in zip(lhs, rhs):
            if lb[0] == 'w' and rb[0] == 'c' and rb[1] in '01':
                const[lb[1]].add(lb[2])
            elif lb[0] == 'w' and rb[0] == 'w':
                alias.append((lb, rb))
    # Kept wires are not merged by opt, so a constant can reach a wire through a chain
    # of wire-to-wire connections (e.g. a child port fed by a parent wire tied to 0).
    changed = True
    while changed:
        changed = False
        for lb, rb in alias:
            if rb[2] in const.get(rb[1], ()) and lb[2] not in const[lb[1]]:
                const[lb[1]].add(lb[2])
                changed = True
    return widths, const


class _Bits(set):
    """Constant bit set of one wire, with the bit range [lo, hi) the wire has."""
    def __init__(self, bits, span):
        super().__init__(bits)
        self.span = span


def _intersect(sets):
    """Bits constant in every set that has them. A width set by a parameter leaves
    the upper bits absent from the narrower builds or instances; a bit needs to be
    constant only where it exists."""
    every = set().union(*(range(*b.span) for b in sets))
    return _Bits(set.intersection(*(b | (every - set(range(*b.span))) for b in sets)),
                 (min(b.span[0] for b in sets), max(b.span[1] for b in sets)))


def _span(wd):
    return (wd[1], wd[1] + wd[0])


def _modules(txt):
    return {m.group(1): m.group(2) for m in re.finditer(r'\nmodule (\S+)\n(.*?)\nend\n', txt, re.S)}


def _base(name):
    bm = re.search(r'\\([A-Za-z_]\w*)', name)             # first identifier: the module, not its parameters
    return bm.group(1) if bm else None


def _yosys_one(params, work, tag, flatten=True, top=None):
    """Elaborate one configuration.

    Returns {module: {plain_signal: [constant bit set per instance]}}. With flatten the
    design is flattened before optimisation, so a constant also propagates through
    instance ports (a literal tied at an instantiation, a child output that is constant);
    each flattened wire is mapped back to its module through the instance paths of the
    unflattened hierarchy. Without it every module is optimised on its own.
    """
    top = top or cfg.TOP
    files = cfg.rtl_files()
    pre, il = os.path.join(work, tag + '.pre.il'), os.path.join(work, tag + '.il')
    # Parameters are set with chparam before hierarchy: `hierarchy -chparam` trips an
    # internal assert on some tops (Yosys 0.69, rtlil_bufnorm.cc).
    cmds = ['read_verilog -nooverwrite -mem2reg ' + ' '.join(files)]
    cmds += ['chparam -set %s %s %s' % (k, v, top) for k, v in sorted(params.items())]
    cmds += ['hierarchy -check -top %s' % top,
             'proc', 'write_rtlil ' + pre, 'setattr -set keep 1 w:*']
    if flatten:
        cmds += ['flatten', 'setattr -set keep 1 w:*']
    cmds += ['opt -full', 'opt -full', 'write_rtlil ' + il]
    with open(il + '.ys', 'w') as fh:
        fh.write('\n'.join(cmds))
    r = subprocess.run(['yosys', '-q', '-l', il + '.log', il + '.ys'], capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError('yosys failed on %s: %s' % (tag, r.stderr[-800:]))
    res = collections.defaultdict(lambda: collections.defaultdict(list))
    if not flatten:
        for name, body in _modules(open(il).read()).items():
            b = _base(name)
            if not b:
                continue
            widths, const = _rtlil_consts(body)
            per = collections.defaultdict(lambda: None)
            for w in widths:                    # several scopes, one plain name: intersect
                plain, cb = w[1:].split('.')[-1], const.get(w, set())
                per[plain] = _Bits(cb, _span(widths[w])) if per[plain] is None else _Bits(per[plain] & cb, per[plain].span)
                if '.' in w[1:]:                # a generate-scoped wire, also under its own name
                    per[w[1:]] = _Bits(cb, _span(widths[w]))
            for plain, cb in per.items():
                res[b][plain].append(cb)
        return res
    # Instance paths of the unflattened hierarchy: path -> module base.
    mods = _modules(open(pre).read())
    topn = next(n for n in mods if _base(n) == top)
    paths, todo = {'': topn}, ['']
    while todo:
        p = todo.pop()
        for c in re.finditer(r'^\s*cell (\S+) (\S+)$', mods[paths[p]], re.M):
            if c.group(1) in mods:
                q = (p + '.' if p else '') + c.group(2)[1:]
                paths[q] = c.group(1)
                todo.append(q)
    ninst = collections.Counter(_base(t) for t in paths.values())
    body = _modules(open(il).read())
    body = next(v for k, v in body.items() if _base(k) == top)
    widths, const = _rtlil_consts(body)
    inst = collections.defaultdict(lambda: collections.defaultdict(lambda: None))
    ordered = sorted((p for p in paths if p), key=len, reverse=True)
    for w in widths:
        name = w[1:]
        p = next((q for q in ordered if name.startswith(q + '.')), '')
        local = name[len(p) + 1:] if p else name
        b, plain, cb = _base(paths[p]), local.split('.')[-1], const.get(w, set())
        cur = inst[(b, plain)][p]
        inst[(b, plain)][p] = _Bits(cb, _span(widths[w])) if cur is None else _Bits(cur & cb, cur.span)
        if '.' in local:                        # a generate-scoped wire, also under its own name
            cur = inst[(b, local)][p]
            inst[(b, local)][p] = _Bits(cb, _span(widths[w])) if cur is None else _Bits(cur & cb, cur.span)
    for (b, plain), byinst in inst.items():
        # The wire exists in every instance -- or it is generate-scoped or an array
        # element, which exists only in the instances whose parameters build it.
        if len(byinst) == ninst[b] or '.' in plain or '[' in plain:
            res[b][plain].extend(byinst.values())
    return res


def yosys_constants(flatten=True):
    """({module: {signal: bits constant in every instance of every coverage config}}, labels)."""
    work = tempfile.mkdtemp(prefix='cov_const_')
    per, nvar, labels = collections.defaultdict(lambda: collections.defaultdict(list)), collections.Counter(), []
    for c in cfg.coverage_configs():             # (label, params[, top module])
        label, params = c[0], c[1]
        labels.append(label)
        for mod, sigs in _yosys_one(params, work, label, flatten, c[2] if len(c) > 2 else None).items():
            nvar[mod] += 1
            for sig, sets in sigs.items():
                # Yosys scopes the blocks of an else-if generate chain under genblk<N>; Verilator does not.
                per[mod][re.sub(r'(^|\.)(?:genblk\d+\.)+', r'\1', sig)].append(_intersect(sets))
    shutil.rmtree(work, ignore_errors=True)
    out = {}
    for mod, sigs in per.items():
        for sig, sets in sigs.items():
            # Present in every configuration; a generate-scoped wire or an array element
            # needs to be constant only in the configurations that build it.
            if len(sets) == nvar[mod] or '.' in sig or '[' in sig:
                c = _intersect(sets)
                if c:
                    out.setdefault(mod, {})[sig] = c
    return out, labels


def main(datdir, write, use_yosys=True):
    wpath = cov_waive.default_path(__file__)
    pts = cov_report.parse(datdir)
    # Judge against the HAND-WRITTEN waivers only: the generated section is what is
    # being recomputed, so it must not decide what is still uncovered.
    wv = cov_waive.Waivers(None)
    if os.path.exists(wpath):
        with open(wpath, encoding='utf-8') as fh:
            txt = fh.read()
        manual = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), '', txt, flags=re.S)
        tmp = wpath[:-3] + '.manual.tmp.md'
        with open(tmp, 'w', encoding='utf-8') as fh:
            fh.write(manual)
        wv = cov_waive.Waivers(tmp)
        os.remove(tmp)
    recs = cov_waive.records_from_report(pts)
    acc = {}
    for page, path, ln, sig, cnt in recs:
        if page == 'v_toggle':
            acc[(path, ln, sig)] = max(acc.get((path, ln, sig), 0), cnt)
    holes = [(p, l, s) for (p, l, s), c in acc.items()
             if c == 0 and not wv.match(p, l, 'v_toggle', s)]

    srcs, const_bits, why = {}, set(), {}
    stats = collections.Counter()
    ycon = None
    if use_yosys and shutil.which('yosys'):
        ycon, labels = yosys_constants('--no-flatten' not in sys.argv)
        print('method: Yosys elaboration (%s) of %s' % ('per module' if '--no-flatten' in sys.argv
                                                           else 'flattened', ', '.join(labels)))
    else:
        print('method: text parser (Yosys %s)' % ('disabled' if shutil.which('yosys') else 'not found'))
    for path, ln, vsig in holes:
        sig = vsig.replace('__05F', '_')        # Verilator escapes '__' in a name as '___05F'
        m = re.match(r'^(\w+)(?:\[(\d+)\])?$', sig)
        m2 = re.match(r'^((?:\w+(?:\[\d+\])?\.)*\w+)\[(\d+)\]\[(\d+)\]$', sig)
        m3 = re.match(r'^((?:\w+(?:\[\d+\])?\.)+\w+)(?:\[(\d+)\])?$', sig)
        if m2 and ycon is not None:             # array element: Yosys names it base[i]
            m, base, bit = m2, '%s[%s]' % (m2.group(1), m2.group(2)), int(m2.group(3))
        elif m3 and ycon is not None:           # generate-scoped: scope.name[bit]
            m, base, bit = m3, m3.group(1), int(m3.group(2) or 0)
        elif not m:
            stats['unparsed name'] += 1
            continue
        else:
            base, bit = m.group(1), int(m.group(2) or 0)
            elem = '%s[%s]' % (m.group(1), m.group(2))
            if m.group(2) is not None and ycon is not None and \
                    elem in ycon.get(os.path.basename(path)[:-2], {}):
                base, bit = elem, 0                 # element of a 1-bit wire array
        src = srcs.get(path) or srcs.setdefault(path, Source(path))
        if ycon is not None:
            if bit in ycon.get(os.path.basename(path)[:-2], {}).get(base, ()):
                stats['constant'] += 1
                const_bits.add((path, ln, vsig))
                drv = src.drivers.get(m.group(1), [])
                at = drv[0][0] if len(drv) == 1 else ln
                why[(path, ln)] = ('constant by construction: tied to a constant in every coverage '
                                   'configuration (%s), driver at %s:%d' % (', '.join(labels),
                                                                           os.path.basename(path), at))
            else:
                stats['not constant'] += 1
            continue
        drv = src.drivers.get(base, [])
        if len(drv) != 1 or src.procedurally_assigned(base):
            stats['no single continuous driver'] += 1
            continue
        if src.in_generate(drv[0][0]):
            stats['driver inside a generate region'] += 1
            continue
        hi, lo = src.widths.get(base, (0, 0))
        flags = concat(src, drv[0][1])
        if flags is None or len(flags) != hi - lo + 1:
            stats['expression not parsed'] += 1
            continue
        if not flags[hi - bit]:
            stats['bit is not constant'] += 1
            continue
        stats['constant'] += 1
        const_bits.add((path, ln, vsig))
        why[(path, ln)] = 'constant by construction: literal bits of the assignment at %s:%d' % (
            os.path.basename(path), drv[0][0])

    entries = []
    for path, ln in sorted({(p, l) for p, l, _ in const_bits}):
        # Offer suggest_entries only the constant bits as holes: every other point on
        # the line is presented as covered, so the fold can never swallow a real hole.
        fake = [(pg, pa, l2, sg, (c if (pa, l2, sg) in const_bits or pg != 'v_toggle' else max(c, 1)))
                for pg, pa, l2, sg, c in recs if pa == path and l2 == ln]
        es, _, _ = cov_waive.suggest_entries(fake, os.path.basename(path), ln, 'toggle')
        for e in es:
            e.pop('_folded', None)
            e['why'] = why[(path, ln)]
            entries.append(e)

    print('uncovered toggle points (after hand-written waivers): %d' % len(holes))
    for k, n in stats.most_common():
        print('   %-30s %6d' % (k, n))
    print('generated entries: %d' % len(entries))
    if not write:
        return 0
    block = [BEGIN, '', '## Constant by construction (generated)', '',
             'Bits tied to a constant in every coverage configuration (Yosys elaboration),',
             'or, without Yosys, sized literals or parameters in their only continuous driver.',
             'Regenerate with `../bin/cov_const.py cov/dats --write` after an RTL change; '
             '`--lint` flags any that went stale.', '', '```json', '[',
             ',\n'.join(json.dumps(e, ensure_ascii=False, separators=(',', ':')) for e in entries),
             ']', '```', '', END]
    with open(wpath, encoding='utf-8') as fh:
        txt = fh.read()
    if BEGIN in txt:
        txt = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), '\n'.join(block), txt, flags=re.S)
    else:
        txt = txt.rstrip('\n') + '\n\n' + '\n'.join(block) + '\n'
    with open(wpath, 'w', encoding='utf-8') as fh:
        fh.write(txt)
    print('wrote %s' % wpath)
    return 0


if __name__ == '__main__':
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    sys.exit(main(args[0] if args else 'cov/dats', '--write' in sys.argv, '--no-yosys' not in sys.argv))
